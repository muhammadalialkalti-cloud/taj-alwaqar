    function clampPage(page) {
        const p = parseInt(page, 10) || 1;
        return Math.min(604, Math.max(1, p));
    }

    // تحديد رقم الجزء (1 - 30) لأي صفحة
    function getJuzForPage(page) {
        const p = clampPage(page);
        for (let i = JUZ_START_PAGES.length - 1; i >= 0; i--) {
            if (p >= JUZ_START_PAGES[i]) {
                return i + 1;
            }
        }
        return 1;
    }

    // حدود صفحات الجزء (البداية والنهاية)
    function getJuzBounds(juzNumber) {
        const j = Math.min(30, Math.max(1, parseInt(juzNumber, 10) || 1));
        const startPage = JUZ_START_PAGES[j - 1];
        const endPage = j < 30 ? JUZ_START_PAGES[j] - 1 : 604;
        return {
            juz: j,
            name: JUZ_NAMES[j - 1],
            startPage,
            endPage,
            totalPages: endPage - startPage + 1
        };
    }

    // تحديد الحزب (1 - 60) والربع داخل الحزب (1 - 4) والربع الكلي (1 - 240)
    function getHizbAndRubForPage(page) {
        const p = clampPage(page);
        const juz = getJuzForPage(p);
        const bounds = getJuzBounds(juz);
        const offsetInJuz = p - bounds.startPage;
        const juzSpan = bounds.totalPages;

        // كل جزء يتكون من حزبين (8 أرباع)
        const rubIndexInJuz = Math.min(7, Math.floor((offsetInJuz / juzSpan) * 8));
        const isSecondHizb = rubIndexInJuz >= 4;
        const hizb = (juz - 1) * 2 + (isSecondHizb ? 2 : 1);
        const rubInHizb = (rubIndexInJuz % 4) + 1; // 1 إلى 4
        const globalRub = (hizb - 1) * 4 + rubInHizb; // 1 إلى 240

        const rubLabels = ["أول الحزب", "الربع الثاني", "نصف الحزب", "الربع الرابع"];

        return {
            juz,
            hizb,
            rubInHizb,
            rubLabel: rubLabels[rubInHizb - 1],
            globalRub
        };
    }

    // حدود صفحات الحزب (1 - 60)
    function getHizbBounds(hizbNumber) {
        const h = Math.min(60, Math.max(1, parseInt(hizbNumber, 10) || 1));
        const juz = Math.ceil(h / 2);
        const isSecondHalf = (h % 2 === 0);
        const jBounds = getJuzBounds(juz);
        const midPage = jBounds.startPage + Math.floor(jBounds.totalPages / 2);

        if (!isSecondHalf) {
            return { hizb: h, juz, startPage: jBounds.startPage, endPage: midPage - 1 };
        } else {
            return { hizb: h, juz, startPage: midPage, endPage: jBounds.endPage };
        }
    }

    // تحويل رقم الربع العام (1 - 240) إلى نطاق صفحات تقريبي دقيق
    function getRubPageRange(globalRubNumber) {
        const r = Math.min(240, Math.max(1, parseInt(globalRubNumber, 10) || 1));
        const juz = Math.ceil(r / 8);
        const rubInJuz = ((r - 1) % 8); // 0..7
        const jBounds = getJuzBounds(juz);
        const startPage = jBounds.startPage + Math.round((rubInJuz * jBounds.totalPages) / 8);
        const nextStart = jBounds.startPage + Math.round(((rubInJuz + 1) * jBounds.totalPages) / 8);
        const endPage = Math.max(startPage, Math.min(jBounds.endPage, nextStart - 1));
        return { globalRub: r, juz, startPage, endPage };
    }

    // استخراج السور الموجودة في صفحة معينة
    function getSurahsOnPage(page) {
        const p = clampPage(page);
        return SURAHS.filter(s => p >= s.startPage && p <= s.endPage);
    }

    // استخراج كامل البيانات الهندسية لصفحة واحدة
    function getPageMetadata(page) {
        const p = clampPage(page);
        const hizbInfo = getHizbAndRubForPage(p);
        const surahs = getSurahsOnPage(p);
        const primarySurah = surahs.length > 0 ? surahs[0] : SURAHS[0];

        return {
            page: p,
            juz: hizbInfo.juz,
            juzName: JUZ_NAMES[hizbInfo.juz - 1],
            hizb: hizbInfo.hizb,
            rubInHizb: hizbInfo.rubInHizb,
            rubLabel: hizbInfo.rubLabel,
            globalRub: hizbInfo.globalRub,
            surahs,
            primarySurah,
            surahNamesText: surahs.map(s => `سورة ${s.name}`).join(" • ")
        };
    }

    // توصيف نطاق من الصفحات (من ص ... إلى ص ...) بالنظامين معاً (الصفحات + الأجزاء والأحزاب والسور)
    function describePageRange(fromPage, toPage, formatNumFn = (n => n)) {
        const start = clampPage(fromPage);
        const end = clampPage(Math.max(start, toPage));
        const metaStart = getPageMetadata(start);
        const metaEnd = getPageMetadata(end);

        const pagesCount = end - start + 1;
        const pageText = start === end
            ? `صفحة ${formatNumFn(start)}`
            : `من ص ${formatNumFn(start)} إلى ص ${formatNumFn(end)} (${formatNumFn(pagesCount)} ص)`;

        const surahText = metaStart.primarySurah.id === metaEnd.primarySurah.id
            ? `سورة ${metaStart.primarySurah.name}`
            : `سورة ${metaStart.primarySurah.name} ⬅ ${metaEnd.primarySurah.name}`;

        const hizbText = metaStart.hizb === metaEnd.hizb
            ? `الجزء ${formatNumFn(metaStart.juz)} • الحزب ${formatNumFn(metaStart.hizb)} (${metaStart.rubLabel})`
            : `الجزء ${formatNumFn(metaStart.juz)} (حزب ${formatNumFn(metaStart.hizb)}) ⬅ الجزء ${formatNumFn(metaEnd.juz)} (حزب ${formatNumFn(metaEnd.hizb)})`;

        return {
            startPage: start,
            endPage: end,
            pagesCount,
            pageText,
            surahText,
            hizbText,
            fullSummary: `${pageText} • ${surahText} • ${hizbText}`
        };
    }

